//Длина шоссейных дорог области равна D км. Прогнозируется ежегодный ее прирост на B км. \
Полагается, что на каждые C км дорог необходим один пост автоинспекции. Для текущего года и \
последующих N лет найти необходимое число постов автоинспекции.

#include <stdio.h>
#include <stdlib.h>
#include <locale.h>

int main(){
    setlocale(LC_ALL, "");

    double D,B,C,d;
    int N, n;

    printf("\nВведите начальную длину дорог D (км): ");
    scanf("%lf", &D);scanf("%*[^\n]");
    printf("\nВведите ежегодный прирост B (км): ");
    scanf("%lf", &B);scanf("%*[^\n]");
    printf("\nВведите норму C (км на один пост): ");
    scanf("%lf", &C);scanf("%*[^\n]");
    printf("\nВведите количество лет прогноза N: ");
    scanf("%d", &N);scanf("%*[^\n]");

    printf("\nВведено начальную длину дорог D (км): %6.3f \n", D);
    printf("Введено ежегодный прирост B (км): %6.3f \n", B);
    printf("Введено норму C (км на один пост): %6.3f \n", C);
    printf("Введено количество лет прогноза N: %2d \n", N);

    if (D < 0 || D >= 1000 || B < 0 || B >= 1000 \
        || C <= 0 || C >= 1000 || N < 1 || N >= 100){
            printf("\nОшибка: нарушен диапазон входных данных\n");
            return 0;
        }

    printf(" _________________________________");
    printf("\n| Год|Длина дорог(км)|Число постов|");
    printf("\n ----+---------------+------------");
    for (int i=0; i <= N; i++){
        d = D+B*i;
        n = (int)(d/C)+1;
    printf("\n| %2d |   %9.3f   |  %8d  |",i,d,n);
    }
    printf("\n ==== =============== ============");

    return 0;}
